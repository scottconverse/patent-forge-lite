//! Synthetic-only migration rehearsal. This is not a production-data importer.
use super::*;
use rusqlite::{backup::Backup, types::ValueRef};
use serde_json::{Map, Value};
use std::{collections::BTreeMap, fs, path::PathBuf};

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ImportReceipt {
    pub source_identity: String,
    pub projects_imported: usize,
    pub runs_imported: usize,
    pub records_preserved: usize,
    pub backup_path: PathBuf,
    pub activated_path: Option<PathBuf>,
    pub repeated: bool,
    #[serde(default)]
    pub warnings: Vec<String>,
}

fn provenance_warnings() -> Vec<String> {
    vec![
        "Historical RunInput is reconstructed from intake available at import; original per-run inputs and prompt snapshots are unavailable.".into(),
        "Original saved report content is preserved when present; it was not generated by Patent Forge Lite.".into(),
        "Archive-only entities and encrypted credentials are preserved but are not yet usable workflow migration parity.".into(),
    ]
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MigrationPhase {
    Backup,
    Stage,
    Activation,
}

#[derive(Debug, Clone, Copy, Default)]
pub struct MigrationOptions {
    /// Deterministic crash-boundary rehearsal; never enabled by normal imports.
    pub interrupt_after: Option<MigrationPhase>,
}

type Snapshot = BTreeMap<String, Vec<Value>>;

/// Authored test data, never copied from a real installation.
pub const LEGACY_SYNTHETIC_FIXTURE_SQL: &str =
    include_str!("../../../fixtures/legacy/representative.sql");

/// Create a representative synthetic legacy database at a NEW explicit path.
/// Refuses an existing file; no discovery, providers, or user data are involved.
pub fn write_legacy_synthetic_fixture(path: &Path) -> Result<()> {
    fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
        .map_err(io)?;
    let mut connection =
        Connection::open_with_flags(path, OpenFlags::SQLITE_OPEN_READ_WRITE).map_err(db)?;
    connection
        .execute_batch("PRAGMA foreign_keys=ON")
        .map_err(db)?;
    let transaction = connection.transaction().map_err(db)?;
    transaction
        .execute_batch(LEGACY_SYNTHETIC_FIXTURE_SQL)
        .map_err(db)?;
    transaction.commit().map_err(db)?;
    integrity(&connection)
}

fn io(error: impl std::fmt::Display) -> Error {
    Error::Io(error.to_string())
}
fn readonly(path: &Path) -> Result<Connection> {
    Connection::open_with_flags(path, OpenFlags::SQLITE_OPEN_READ_ONLY).map_err(db)
}
fn integrity(connection: &Connection) -> Result<()> {
    let check: String = connection
        .query_row("PRAGMA integrity_check", [], |r| r.get(0))
        .map_err(db)?;
    if check != "ok" {
        return Err(db(format!("SQLite integrity check failed: {check}")));
    }
    let mut statement = connection.prepare("PRAGMA foreign_key_check").map_err(db)?;
    if statement
        .query([])
        .map_err(db)?
        .next()
        .map_err(db)?
        .is_some()
    {
        return Err(db("legacy foreign-key validation failed"));
    }
    Ok(())
}
fn identity(connection: &Connection) -> Result<String> {
    let marker: Option<String> = connection
        .query_row(
            "SELECT value FROM PFLFixture WHERE key='synthetic'",
            [],
            |r| r.get(0),
        )
        .optional()
        .map_err(|_| Error::Invalid("explicit synthetic fixture marker required".into()))?;
    if marker.as_deref() != Some("true") {
        return Err(Error::Invalid(
            "only synthetic legacy fixtures may be imported".into(),
        ));
    }
    let id: String = connection
        .query_row(
            "SELECT value FROM PFLFixture WHERE key='fixture_id'",
            [],
            |r| r.get(0),
        )
        .map_err(|_| Error::Invalid("synthetic fixture identity required".into()))?;
    if id.trim().is_empty() {
        return Err(Error::Invalid("empty fixture identity".into()));
    }
    Ok(id)
}
/// Replacement recorded where a credential used to be. Deliberately not reversible.
pub const REDACTED_CREDENTIAL: &str = "[redacted at import: re-enter this credential]";

/// Columns whose contents are secrets. Matched on the name so a new legacy column of the
/// same kind is redacted even though the importer has never seen it.
fn is_credential_column(name: &str) -> bool {
    let lower = name.to_ascii_lowercase();
    let compact: String = lower
        .chars()
        .filter(|c| c.is_ascii_alphanumeric())
        .collect();
    // Suffix matching, not substring: `maxTokens` is a budget, not a secret.
    compact.ends_with("apikey")
        || compact.ends_with("token")
        || compact.ends_with("secret")
        || compact.ends_with("password")
        || compact.ends_with("salt")
}

fn snapshot(connection: &Connection) -> Result<Snapshot> {
    let mut statement = connection.prepare(
        "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
    ).map_err(db)?;
    let tables: Vec<String> = statement
        .query_map([], |r| r.get(0))
        .map_err(db)?
        .collect::<std::result::Result<_, _>>()
        .map_err(db)?;
    let mut result = BTreeMap::new();
    for table in tables {
        let sql = format!(
            "SELECT * FROM \"{}\" ORDER BY rowid",
            table.replace('"', "\"\"")
        );
        let mut statement = connection.prepare(&sql).map_err(db)?;
        let columns: Vec<String> = statement.column_names().map(|s| s.to_string()).collect();
        let mut rows = statement.query([]).map_err(db)?;
        let mut records = vec![];
        while let Some(row) = rows.next().map_err(db)? {
            let mut record = Map::new();
            for (index, name) in columns.iter().enumerate() {
                let value = match row.get_ref(index).map_err(db)? {
                    ValueRef::Null => Value::Null,
                    ValueRef::Integer(n) => Value::from(n),
                    ValueRef::Real(n) => serde_json::Number::from_f64(n)
                        .map(Value::Number)
                        .ok_or_else(|| db("non-finite legacy SQLite number"))?,
                    ValueRef::Text(s) => Value::String(String::from_utf8(s.to_vec()).map_err(db)?),
                    ValueRef::Blob(bytes) => {
                        let hex: String = bytes.iter().map(|b| format!("{b:02x}")).collect();
                        serde_json::json!({ "sqlite_blob_hex": hex })
                    }
                };
                // A credential is never carried across a migration, not even into the
                // opaque archive: the column is recorded as redacted so nothing about the
                // value survives, and the operator re-enters it for the new session.
                let value = if is_credential_column(name) {
                    Value::String(REDACTED_CREDENTIAL.into())
                } else {
                    value
                };
                record.insert(name.clone(), value);
            }
            records.push(Value::Object(record));
        }
        result.insert(table, records);
    }
    Ok(result)
}
fn text(value: &Value, key: &str) -> String {
    value
        .get(key)
        .and_then(Value::as_str)
        .unwrap_or_default()
        .to_string()
}
fn timestamp(value: &Value, key: &str) -> u64 {
    value
        .get(key)
        .and_then(|v| v.as_u64().or_else(|| v.as_str()?.parse().ok()))
        .unwrap_or(0)
}
fn records<'a>(snapshot: &'a Snapshot, table: &str) -> &'a [Value] {
    snapshot.get(table).map(Vec::as_slice).unwrap_or_default()
}
fn terminal(value: &str) -> RunOutcome {
    match value {
        "COMPLETE" | "COMPLETED" => RunOutcome::Completed,
        "FAILED" | "ERROR" => RunOutcome::Failed,
        "CANCELLED" | "CANCELED" => RunOutcome::Cancelled,
        _ => RunOutcome::Interrupted,
    }
}
fn workspace(path: &Path, fixture_id: &str) -> Result<()> {
    let marker = path.join(".pfl-synthetic-migration");
    if marker.exists() {
        if fs::read_to_string(&marker).map_err(io)? != fixture_id {
            return Err(Error::Conflict(
                "migration workspace belongs to another fixture".into(),
            ));
        }
        return Ok(());
    }
    if path.exists() && fs::read_dir(path).map_err(io)?.next().is_some() {
        return Err(Error::Conflict(
            "migration workspace must be empty or owned by this fixture".into(),
        ));
    }
    fs::create_dir_all(path).map_err(io)?;
    // create_new prevents replacing another operation's ownership marker.
    use std::io::Write;
    let mut file = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(marker)
        .map_err(io)?;
    file.write_all(fixture_id.as_bytes()).map_err(io)?;
    file.sync_all().map_err(io)?;
    Ok(())
}

fn backup(source_path: &Path, work: &Path) -> Result<(String, Snapshot, PathBuf, Connection)> {
    let source = readonly(source_path)?;
    let id = identity(&source)?;
    // One pinned read transaction covers validation, all WAL-committed records,
    // and backup. A producer cannot make the archive and comparison disagree.
    source.execute_batch("BEGIN").map_err(db)?;
    integrity(&source)?;
    let original = snapshot(&source)?;
    workspace(work, &id)?;
    // SQLite releases this exclusive migration lease after a real process
    // crash, unlike a stale lock-file sentinel. It covers activation as well.
    let lease = Connection::open(work.join("migration-owner.sqlite3")).map_err(db)?;
    lease.busy_timeout(Duration::from_secs(5)).map_err(db)?;
    lease
        .execute_batch(
            "CREATE TABLE IF NOT EXISTS migration_owner(id INTEGER PRIMARY KEY);
         BEGIN EXCLUSIVE;",
        )
        .map_err(db)?;
    let destination = work.join("legacy-backup.sqlite3");
    let pending = work.join("legacy-backup.pending.sqlite3");
    if !destination.exists() {
        if !pending.exists() {
            let mut copy = Connection::open(&pending).map_err(db)?;
            {
                let operation = Backup::new(&source, &mut copy).map_err(db)?;
                operation
                    .run_to_completion(64, Duration::from_millis(1), None)
                    .map_err(db)?;
            }
            integrity(&copy)?;
            if identity(&copy)? != id || snapshot(&copy)? != original {
                return Err(db("backup does not match the committed source snapshot"));
            }
            drop(copy);
            fs::OpenOptions::new()
                .read(true)
                .write(true)
                .open(&pending)
                .map_err(io)?
                .sync_all()
                .map_err(io)?;
        }
        // A prior interruption may have left a complete pending backup; validate
        // it rather than truncating, overwriting, or silently accepting it.
        let copy = readonly(&pending)?;
        integrity(&copy)?;
        if identity(&copy)? != id || snapshot(&copy)? != original {
            return Err(Error::Conflict(
                "pending backup differs; original preserved".into(),
            ));
        }
        drop(copy);
        fs::rename(&pending, &destination).map_err(io)?;
    }
    let copy = readonly(&destination)?;
    integrity(&copy)?;
    if identity(&copy)? != id || snapshot(&copy)? != original {
        return Err(Error::Conflict(
            "fixture changed since backup; choose a new workspace".into(),
        ));
    }
    Ok((id, original, destination, lease))
}

impl SqliteStore {
    /// Copy-first import into this Lite store, with one transaction for records,
    /// domain projections, settings, events and the idempotence ledger.
    pub fn import_legacy_synthetic(&self, source: &Path, work: &Path) -> Result<ImportReceipt> {
        let (id, original, backup_path, _lease) = backup(source, work)?;
        self.import_snapshot(&id, &original, backup_path)
    }

    fn import_snapshot(
        &self,
        id: &str,
        original: &Snapshot,
        backup_path: PathBuf,
    ) -> Result<ImportReceipt> {
        self.transaction(|tx| {
            let serialized = encode(original)?;
            let prior: Option<(String, String)> = tx
                .query_row(
                    "SELECT snapshot,receipt FROM legacy_imports WHERE identity=?1",
                    [id],
                    |r| Ok((r.get(0)?, r.get(1)?)),
                )
                .optional()
                .map_err(db)?;
            if let Some((old, receipt)) = prior {
                if old != serialized {
                    return Err(Error::Conflict(
                        "fixture identity reused with changed records".into(),
                    ));
                }
                let mut receipt: ImportReceipt = decode(&receipt)?;
                receipt.repeated = true;
                if receipt.warnings.is_empty() {
                    receipt.warnings = provenance_warnings();
                }
                return Ok(receipt);
            }
            let receipt = ImportReceipt {
                source_identity: id.to_string(),
                projects_imported: records(original, "Project").len(),
                runs_imported: records(original, "FeasibilityRun").len(),
                records_preserved: original.values().map(Vec::len).sum(),
                backup_path,
                activated_path: None,
                repeated: false,
                warnings: provenance_warnings(),
            };
            tx.execute(
                "INSERT INTO legacy_imports VALUES(?1,?2,?3)",
                params![id, serialized, encode(&receipt)?],
            )
            .map_err(db)?;
            for (table, rows) in original {
                for (index, record) in rows.iter().enumerate() {
                    tx.execute(
                        "INSERT INTO legacy_records VALUES(?1,?2,?3,?4)",
                        params![id, table, index as i64, encode(record)?],
                    )
                    .map_err(db)?;
                }
            }
            for record in records(original, "Project") {
                let project_id = ProjectId(text(record, "id"));
                if project_id.0.is_empty() {
                    return Err(Error::Invalid("legacy project missing ID".into()));
                }
                let invention = records(original, "InventionInput")
                    .iter()
                    .find(|v| text(v, "projectId") == project_id.0);
                let intake = Intake {
                    title: invention
                        .map(|v| text(v, "title"))
                        .filter(|s| !s.is_empty())
                        .unwrap_or_else(|| text(record, "title")),
                    description: invention
                        .map(|v| text(v, "description"))
                        .unwrap_or_default(),
                    technical_field: invention
                        .and_then(|v| v.get("technical_field").or_else(|| v.get("technicalField")))
                        .and_then(Value::as_str)
                        .unwrap_or_default()
                        .to_string(),
                    context: invention
                        .map(|v| serde_json::from_value::<InventionContext>(v.clone()).map_err(db))
                        .transpose()?
                        .unwrap_or_default(),
                };
                let project = Project {
                    id: project_id,
                    intake,
                    created_at_ms: timestamp(record, "createdAt"),
                    updated_at_ms: timestamp(record, "updatedAt"),
                };
                tx.execute(
                    "INSERT INTO projects VALUES(?1,?2)",
                    params![project.id.0, encode(&project)?],
                )
                .map_err(db)?;
                let edit = IntakeRevision {
                    revision: 1,
                    intake: project.intake.clone(),
                    at_ms: project.updated_at_ms,
                };
                tx.execute(
                    "INSERT INTO intake_revisions VALUES(?1,1,?2)",
                    params![project.id.0, encode(&edit)?],
                )
                .map_err(db)?;
            }
            for record in records(original, "FeasibilityRun") {
                let run_id = RunId(text(record, "id"));
                let project_id = ProjectId(text(record, "projectId"));
                let project = load_project(tx, &project_id)?;
                let attempt_id = AttemptId(format!("{}:legacy-attempt", run_id.0));
                let outcome = terminal(&text(record, "status"));
                let version = record
                    .get("version")
                    .and_then(Value::as_u64)
                    .and_then(|n| u32::try_from(n).ok())
                    .filter(|n| *n > 0)
                    .ok_or_else(|| Error::Invalid("invalid legacy run version".into()))?;
                let mut checkpoints = vec![];
                for stage in records(original, "FeasibilityStage")
                    .iter()
                    .filter(|v| text(v, "feasibilityRunId") == run_id.0)
                {
                    if !matches!(text(stage, "status").as_str(), "COMPLETE" | "COMPLETED") {
                        continue;
                    }
                    let number = stage
                        .get("stageNumber")
                        .and_then(Value::as_u64)
                        .unwrap_or(0);
                    let index = usize::try_from(number)
                        .ok()
                        .and_then(|n| n.checked_sub(1))
                        .filter(|n| *n < Stage::ALL.len())
                        .ok_or_else(|| Error::Invalid("invalid legacy stage number".into()))?;
                    if checkpoints
                        .iter()
                        .any(|c: &Checkpoint| c.stage == Stage::ALL[index])
                    {
                        return Err(Error::Conflict("duplicate legacy completed stage".into()));
                    }
                    checkpoints.push(Checkpoint {
                        stage: Stage::ALL[index],
                        attempt_id: attempt_id.clone(),
                        text: text(stage, "outputText"),
                        usage: Usage {
                            input_tokens: stage.get("inputTokens").and_then(Value::as_u64),
                            output_tokens: stage.get("outputTokens").and_then(Value::as_u64),
                        },
                        completed_at_ms: timestamp(stage, "completedAt"),
                    });
                }
                checkpoints.sort_by_key(|c| c.stage);
                // Preserve gaps verbatim in the archive, but do not make a
                // non-contiguous checkpoint chain executable as a resumed run.
                if checkpoints
                    .iter()
                    .enumerate()
                    .any(|(i, c)| c.stage.number() != i + 1)
                {
                    return Err(Error::Conflict(
                        "legacy checkpoints contain a gap; source preserved".into(),
                    ));
                }
                let report = record
                    .get("finalReport")
                    .and_then(Value::as_str)
                    .map(|markdown| SavedReport {
                        run_id: run_id.clone(),
                        version,
                        markdown: markdown.to_string(),
                    });
                let mut run = RunSnapshot {
                    id: run_id,
                    project_id,
                    version,
                    idempotency_key: format!("legacy:{id}:{}", text(record, "id")),
                    input: RunInput {
                        kind: WorkflowKind::Feasibility,
                        intake: project.intake,
                        provider: ProviderSnapshot {
                            kind: ProviderKind::Replay,
                            model: "legacy-import-no-execution".into(),
                            endpoint: None,
                        },
                        prompts: PromptSnapshot {
                            version: "legacy-unavailable".into(),
                            sha256: String::new(),
                        },
                        authorization: Authorization::default(),
                        regeneration: None,
                        upstream: Upstream::default(),
                    },
                    rerun_of: None,
                    created_at_ms: timestamp(record, "startedAt"),
                    outcome,
                    attempts: vec![Attempt {
                        id: attempt_id.clone(),
                        number: 1,
                        started_at_ms: timestamp(record, "startedAt"),
                        finished_at_ms: Some(timestamp(record, "completedAt")),
                        outcome,
                    }],
                    checkpoints,
                    last_sequence: 0,
                    report,
                };
                tx.execute(
                    "INSERT INTO runs VALUES(?1,?2,?3,?4,?5)",
                    params![
                        run.id.0,
                        run.project_id.0,
                        run.version,
                        run.idempotency_key,
                        encode(&run)?
                    ],
                )
                .map_err(db)?;
                let checkpoints = run.checkpoints.clone();
                for checkpoint in checkpoints {
                    push_event(
                        tx,
                        &mut run,
                        Some(attempt_id.clone()),
                        EventKind::CheckpointSaved {
                            stage: checkpoint.stage,
                            usage: checkpoint.usage,
                        },
                        checkpoint.completed_at_ms,
                    )?;
                }
                let at = timestamp(record, "completedAt");
                push_event(
                    tx,
                    &mut run,
                    Some(attempt_id),
                    EventKind::OutcomeChanged {
                        outcome,
                        message: Some(
                            "Synthetic legacy history imported; not generated by Lite".into(),
                        ),
                    },
                    at,
                )?;
                save_run(tx, &run)?;
            }
            for stage in records(original, "FeasibilityStage") {
                load_run(tx, &RunId(text(stage, "feasibilityRunId")))?;
            }
            if let Some(record) = records(original, "AppSettings").first() {
                let has_settings: bool = tx
                    .query_row("SELECT EXISTS(SELECT 1 FROM settings)", [], |r| r.get(0))
                    .map_err(db)?;
                if has_settings {
                    return Err(Error::Conflict(
                        "existing Lite settings require an explicit merge policy".into(),
                    ));
                }
                let settings = Settings {
                    profile: if text(record, "installEdition") == "Full" {
                        SetupProfile::Full
                    } else {
                        SetupProfile::Lean
                    },
                    local_endpoint: record
                        .get("ollamaUrl")
                        .and_then(Value::as_str)
                        .map(str::to_string),
                    local_model: record
                        .get("localDefaultModel")
                        .or_else(|| record.get("ollamaModel"))
                        .and_then(Value::as_str)
                        .map(str::to_string),
                    // Legacy settings never carried a research endpoint.
                    research_endpoint: None,
                    profile_chosen: true,
                };
                tx.execute("INSERT INTO settings VALUES(1,?1)", [encode(&settings)?])
                    .map_err(db)?;
            }
            Ok(receipt)
        })
    }

    /// Lossless source-field archive, including unknown fields, costs, links,
    /// edits and ciphertext. Callers must not display/log secret-bearing tables.
    pub fn legacy_records(&self, identity: &str, table: &str) -> Result<Vec<Value>> {
        self.transaction(|tx| {
            let mut statement = tx.prepare("SELECT payload FROM legacy_records WHERE identity=?1 AND table_name=?2 ORDER BY ordinal").map_err(db)?;
            let rows = statement.query_map(params![identity, table], |r| r.get::<_, String>(0)).map_err(db)?;
            rows.map(|r| decode(&r.map_err(db)?)).collect()
        })
    }
}

/// What an import would move, computed from the source alone: no destination is
/// touched, so a preview cannot be mistaken for a commit.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ImportPreview {
    pub source_identity: String,
    pub projects: usize,
    pub runs: usize,
    pub archived_records: usize,
    /// Tables the importer preserves verbatim but does not interpret.
    pub unknown_tables: Vec<String>,
    pub warnings: Vec<String>,
}

/// Reads the source and reports what an import would carry. Refuses a file that is not
/// a legacy database, so "nothing to import" is never confused with "not readable".
pub fn preview_legacy_synthetic(source: &Path) -> Result<ImportPreview> {
    if !source.exists() {
        return Err(Error::Invalid(format!(
            "no legacy database at {}",
            source.display()
        )));
    }
    let connection =
        rusqlite::Connection::open_with_flags(source, rusqlite::OpenFlags::SQLITE_OPEN_READ_ONLY)
            .map_err(db)?;
    let identity = identity(&connection)?;
    let mut tables: Vec<String> = Vec::new();
    let mut statement = connection
        .prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
        .map_err(db)?;
    let rows = statement
        .query_map([], |row| row.get::<_, String>(0))
        .map_err(db)?;
    for row in rows {
        tables.push(row.map_err(db)?);
    }
    let count = |table: &str| -> Result<usize> {
        let sql = format!("SELECT COUNT(*) FROM \"{table}\"");
        connection
            .query_row(&sql, [], |row| row.get::<_, i64>(0))
            .map(|value| value as usize)
            .map_err(db)
    };
    let projects = if tables.iter().any(|table| table == "Project") {
        count("Project")?
    } else {
        0
    };
    let runs = if tables.iter().any(|table| table == "FeasibilityRun") {
        count("FeasibilityRun")?
    } else {
        0
    };
    // Everything the importer preserves but does not interpret.
    let known = [
        "PFLFixture",
        "Project",
        "InventionInput",
        "FeasibilityRun",
        "FeasibilityStage",
    ];
    let mut unknown_tables: Vec<String> = tables
        .iter()
        .filter(|table| !known.contains(&table.as_str()))
        .cloned()
        .collect();
    unknown_tables.sort();
    let mut archived_records = 0usize;
    for table in &unknown_tables {
        archived_records += count(table)?;
    }
    Ok(ImportPreview {
        source_identity: identity,
        projects,
        runs,
        archived_records,
        unknown_tables,
        warnings: provenance_warnings(),
    })
}
pub fn migrate_legacy_synthetic(source: &Path, destination: &Path) -> Result<ImportReceipt> {
    migrate_legacy_synthetic_with_options(source, destination, MigrationOptions::default())
}

/// Rehearse copy, transactional migration, validation, then atomic activation
/// of a NEW Lite database. Existing destinations are never replaced.
pub fn migrate_legacy_synthetic_with_options(
    source: &Path,
    destination: &Path,
    options: MigrationOptions,
) -> Result<ImportReceipt> {
    let (id, original, backup_path, _lease) = backup(source, destination)?;
    let interrupt = |phase| -> Result<()> {
        if options.interrupt_after == Some(phase) {
            Err(Error::Io(format!("synthetic interruption after {phase:?}")))
        } else {
            Ok(())
        }
    };
    interrupt(MigrationPhase::Backup)?;
    let active = destination.join("patent-forge-lite.sqlite3");
    let staging = destination.join("staged-lite.sqlite3");
    if active.exists() {
        let store = SqliteStore::open(&active)?;
        let mut receipt: ImportReceipt = store.transaction(|tx| {
            let prior: Option<(String, String)> = tx
                .query_row(
                    "SELECT snapshot,receipt FROM legacy_imports WHERE identity=?1",
                    [&id],
                    |r| Ok((r.get(0)?, r.get(1)?)),
                )
                .optional()
                .map_err(db)?;
            let (saved, receipt) = prior.ok_or_else(|| {
                Error::Conflict("activation target is not this completed import".into())
            })?;
            if saved != encode(&original)? {
                return Err(Error::Conflict("activation snapshot differs".into()));
            }
            decode(&receipt)
        })?;
        receipt.repeated = true;
        if receipt.warnings.is_empty() {
            receipt.warnings = provenance_warnings();
        }
        receipt.activated_path = Some(active);
        return Ok(receipt);
    }
    let store = SqliteStore::open(&staging)?;
    let mut receipt = store.import_snapshot(&id, &original, backup_path)?;
    {
        let connection = store
            .connection
            .lock()
            .map_err(|_| db("database mutex poisoned"))?;
        integrity(&connection)?;
    }
    store.checkpoint()?;
    drop(store);
    fs::OpenOptions::new()
        .read(true)
        .write(true)
        .open(&staging)
        .map_err(io)?
        .sync_all()
        .map_err(io)?;
    interrupt(MigrationPhase::Stage)?;
    // A same-filesystem hard link atomically publishes the standalone file and
    // cannot replace an existing destination (unlike POSIX rename). Failure
    // leaves the validated staging file and original backup available.
    fs::hard_link(&staging, &active).map_err(io)?;
    fs::remove_file(&staging).map_err(io)?;
    receipt.activated_path = Some(active);
    interrupt(MigrationPhase::Activation)?;
    Ok(receipt)
}
